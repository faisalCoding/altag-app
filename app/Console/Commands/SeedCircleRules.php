    public function handle(): int
    {
        $added = 0;
        $position = (int) RuleSection::max('position');

        DB::transaction(function () use (&$added, &$position) {
            foreach (self::SECTIONS as $section) {
                // Run again, it leaves alone a section the draft already holds,
                // edited by the manager or not.
                if (RuleSection::where('title', $section['title'])->exists()) {
                    $this->line("تخطّي «{$section['title']}»: القسم موجود في المسودة.");

                    continue;
                }

                $record = RuleSection::create(['title' => $section['title'], 'position' => ++$position]);

                foreach ($section['clauses'] as $index => $body) {
                    $record->clauses()->create(['audience' => $section['audience'], 'body' => $body, 'position' => $index + 1]);
                }

                $added++;
                $this->line("أُضيف «{$section['title']}» (".count($section['clauses']).' بنداً).');
            }
        });

        if (! $this->option('publish')) {
            $this->info("أُضيف {$added} من الأقسام إلى المسودة. راجعها في صفحة «أنظمة الحلقات» ثم انشرها.");

            return self::SUCCESS;
        }

        if (CircleRules::draft() === (CircleRules::current()?->content ?? [])) {
            $this->info('المسودة مطابقة للإصدار المنشور، فلم يُنشر إصدار جديد.');

            return self::SUCCESS;
        }

        $version = CircleRules::publish(null, true, 'أنظمة المجمع لعام ١٤٤٨هـ للمعلمين ومشرفي المراحل.');
        $this->info("نُشر الإصدار {$version->number}، وأُرسل إلى المعلمين والمشرفين ليُقِرّوا به.");

        return self::SUCCESS;
    }
